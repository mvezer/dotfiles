local core = require("core")

local function smart_dd()
	if vim.api.nvim_get_current_line():match("^%s*$") then
		vim.api.nvim_feedkeys('"_dd', "n", false)
	else
		vim.api.nvim_feedkeys("dd", "n", false)
	end
end

